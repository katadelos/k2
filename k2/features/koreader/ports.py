"""Contracts shared by KOReader's production and simulator backends."""

from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Protocol

type Progress = Callable[[str, float], None]


class ReaderDevice(Protocol):
    family: str
    store: Path


class PluginBackend(Protocol):
    def list_installed(self) -> list[dict]: ...
    def settings_status(self) -> dict: ...
    def set_enabled(self, plugin_id: str, enabled: bool) -> dict: ...
    def install(
        self,
        source: str,
        progress: Progress | None = None,
        expected_plugin: str | None = None,
        receipt: dict[str, str] | None = None,
    ) -> dict: ...
    def remove(self, plugin_id: str) -> dict: ...


class CustomisationBackend(Protocol):
    def snapshot(self, refresh: bool = False) -> dict: ...
    def plan(self, action: str, item_id: str) -> dict: ...
    def apply(self, action: str, item_id: str) -> dict: ...


class ReaderBackend(Protocol):
    def status(self) -> dict: ...
    def check_release(self) -> dict: ...
    def select_installation(self, path: str) -> dict: ...
    def install(self) -> dict: ...
    def uninstall(self, identity: Sequence[int]) -> dict: ...
    def add_scriptlet(self) -> dict: ...
    def launch_command(self) -> list[str]: ...
